// Convenience lookup so both tabs and Node tests can resolve by id.
export function glossaryTerm(id) {
  return GLOSSARY.find(g => g.id === id) || null;
}

// Whole-word terms used by gloss-hover.js when decorating body text.
// Multi-word terms first so a shorter match does not claim part of them,
// then the remaining terms, longest first in both pass.
const byTermLength = (a, b) => b.term.length - a.term.length;
const multiWord = GLOSSARY.filter(g => g.term.includes(' ')).sort(byTermLength);
const singleWord = GLOSSARY.filter(g => !g.term.includes(' ')).sort(byTermLength);
export const GLOSSARY_LINK_TERMS = [...multiWord, ...singleWord];
