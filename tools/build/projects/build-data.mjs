// e02s01t01: parse projects.md (3 tables of 50) into js/data/projects.js.
// Canonical plan: specs/product/PROJECTS_SITE_LATEST.md.
// Usage: node build-data.mjs   (writes js/data/projects.js)
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import {
  bucketFromPurpose, subGroupFromNum, languagesFromStack, modeFromCell, slugFromName,
} from './js/data/buckets.js';

const here = dirname(fileURLToPath(import.meta.url));
const md = readFileSync(join(here, 'projects.md'), 'utf8');

function tableRows(headerLineIdx) {
  const lines = md.slice(0).split('\n');
  const rows = [];
  for (let i = headerLineIdx + 2; i < lines.length; i++) {
    const l = lines[i];
    if (/^\|/.test(l) === false) break;      // end of table
    if (/^\|[\s:|-]+\|/.test(l)) continue;   // separator
    const cells = l.replace(/^\|/, '').replace(/\|$/, '').split('|').map(c => c.trim());
    const num = parseInt(cells[0], 10);
    if (!Number.isFinite(num)) continue;
    rows.push({ num, cells });
  }
  return rows;
}

const headers = md.split('\n').map((l, i) => [i, l]).filter(([, l]) => l.startsWith('| # |'));
if (headers.length !== 3) throw new Error('expected 3 tables, found ' + headers.length);
const [h1, h2, h3] = headers.map(([i]) => i);
const tables = [
  { part: 1, rows: tableRows(h1) },
  { part: 2, rows: tableRows(h2) },
  { part: 3, rows: tableRows(h3) },
];

const problems = [];
const records = [];
for (const { part, rows } of tables) {
  if (rows.length !== 50) problems.push(`part ${part}: ${rows.length} rows (expected 50)`);
  const nums = new Set(rows.map(r => r.num));
  if (nums.size !== 50) problems.push(`part ${part}: non-unique # values`);
  for (const { num, cells } of rows) {
    if (cells.length < 6) { problems.push(`part ${part} row ${num}: only ${cells.length} cells`); continue; }
    const name = cells[1];
    const modeCell = cells[2];
    const stack = cells[3];
    const description = cells[5];
    const record = {
      id: slugFromName(name, num),
      name,
      part,
      mode: modeFromCell(modeCell),
      stack,
      languages: languagesFromStack(stack),
      description,
    };
    if (part === 3) {
      record.category = 'education';
      record.subGroup = subGroupFromNum(num);
      record.audience = cells[4];
    } else {
      record.category = bucketFromPurpose(cells[4]);
    }
    if (!record.id) problems.push(`part ${part} row ${num}: empty id`);
    if (!description) problems.push(`part ${part} row ${num}: empty description`);
    if (record.mode === 'either' && !/online.*offline|either/i.test(modeCell)) {
      problems.push(`part ${part} row ${num}: mode cell "${modeCell}" not online/offline/either plain`);
    }
    records.push(record);
  }
}

if (problems.length) {
  console.error('DATA PROBLEMS:');
  for (const p of problems) console.error('  ' + p);
  process.exit(1);
}

// id uniqueness across all 150
const ids = new Map();
for (const r of records) {
  if (ids.has(r.id)) problems.push(`duplicate id ${r.id} (${r.part})`);
  ids.set(r.id, r.id);
}

const parts = {};
for (const r of records) parts[r.part] = (parts[r.part] ?? 0) + 1;
console.log(`records: ${records.length} (1:${parts[1]} 2:${parts[2]} 3:${parts[3]})`);
const cats = {};
for (const r of records) cats[r.category] = (cats[r.category] ?? 0) + 1;
console.log('categories:', JSON.stringify(cats, null, 0));

const out = `// Generated by build-data.mjs from projects.md. Do not edit by hand.
// 150 projects, 3 parts x 50. e02 / one-afternoon-coding-projects-site.
export const PROJECTS = ${JSON.stringify(records, null, 2)};
`;
writeFileSync(join(here, 'js/data/projects.js'), out);
console.log('wrote js/data/projects.js');
