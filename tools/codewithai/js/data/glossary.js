/** Look one term up by id. Returns undefined for unknown ids. */
export function glossaryTerm(id) {
  return GLOSSARY.find((t) => t.id === id);
}

/** The fields for one term in one language ('en' | 'zh'). */
export function termIn(t, lang) {
  if (!t) return null;
  const zh = lang === 'zh';
  return {
    id: t.id,
    term: t.term,                       // always English, in both languages
    subtitle: zh ? t.term_zh : null,    // Chinese term sits under it
    short: zh ? t.short_zh : t.short,
    full: zh ? t.full_zh : t.full,
    links: t.links ?? [],
  };
}

/** Terms of one group, in data order. */
export function termsInGroup(groupId, terms = GLOSSARY) {
  return terms.filter((t) => t.group === groupId);
}
